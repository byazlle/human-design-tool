/** 自定义维度的兜底结构 */
export function customDimension(topic: string): CompositeDimension {
  return {
    key: 'custom',
    label: `自定义 · ${topic}`,
    scene: `围绕「${topic}」这一具体议题解读合盘`,
    requires: ['双方完整盘面', '共享与独有通道', '九中心状态'],
    focus: [topic],
    prompt: `请围绕「${topic}」这一议题，结合两人合盘的共享通道、独有通道与中心状态，给出具体分析与可执行建议。先说明这个议题在盘面上主要体现于哪些结构，再给结论。`,
  }
}
