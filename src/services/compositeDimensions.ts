/**
 * 合盘解读维度。
 *
 * 设计原则：
 * - 同一份合盘数据，换维度 = 换提示词与关注焦点，不重复拉取数据（缓存键含维度）。
 * - 每个维度明确三件事：应用场景、需要读取的盘面内容、解读焦点。
 *   这三项同时展示在界面上，让用户知道「这个解读在看什么、能用来做什么」。
 */
export interface CompositeDimension {
  key: string
  label: string
  /** 一句话场景说明 */
  scene: string
  /** 该维度需要读取哪些盘面内容（界面展示） */
  requires: string[]
  /** 交给 AI 的解读框架（作为事实基础的一部分） */
  focus: string[]
  /** 提示词主体 */
  prompt: string
}

