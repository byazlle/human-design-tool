export function getGate(gate: number): { title: string; keyword: string; text: string } {
  const meta = GATE_NAMES[gate]
  const raw = RAW[gate]
  return {
    title: `闸门 ${gate} · ${meta?.zh ?? ''}`,
    keyword: raw?.keyword ?? '',
    text: raw ? `${raw.defined}\n\n【开放时】${raw.open}` : '暂无该闸门的离线释义。',
  }
}

